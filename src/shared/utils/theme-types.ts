// src/shared/utils/theme-types.ts
import type { ThemeConfig } from '../types'
import { isSelectableGroup } from './theme-resolve'

/** `'a' | 'b'`, or `never` for none. `JSON.stringify` quotes and escapes each name; it is a valid string literal type. */
const union = (names: string[]) => names.length ? names.map(name => JSON.stringify(name)).join(' | ') : 'never'

/**
 * The `.d.ts` that tells TypeScript which themes the project has: the theme
 * names a visitor can pick and the variant ids, from the resolved config
 * (`theme.json` plus the project's `color.themes`). It fills `VenixThemeRegistry`
 * (`shared/types/theme-names.ts`), so `theme.set('natal')` autocompletes.
 */
export function renderThemeTypes(colors: ThemeConfig['colors']): string {
  const themes = Object.keys(colors.groups ?? {}).filter(name => isSelectableGroup(colors, name))
  const variants = Object.keys(colors.themes ?? {})

  return `// Generated by @venix-sistemas/jade: the themes of this project. Do not edit.
declare global {
  interface VenixThemeRegistry {
    themes: ${union(themes)}
    variants: ${union(variants)}
  }
}

export {}
`
}
